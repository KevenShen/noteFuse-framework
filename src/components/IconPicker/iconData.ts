export const getIconComponent = (name: string): ComponentType<any> | null => {
  const item = iconList.find((i) => i.name === name);
  return item?.component || null;
};

// 根据名称获取中文标签
export const getIconLabel = (name: string): string => {
  const item = iconList.find((i) => i.name === name);
  return item?.label || name;
};
